#!/usr/bin/env python3
"""Stamp a new build: bumps ?v=N in index.html and regenerates sw.js with the precache list. usage: tools/mksw.py [N]"""
import os,re,sys,glob
os.chdir(os.path.join(os.path.dirname(__file__),'..'))
html=open('index.html').read()
cur=int(re.search(r'\?v=(\d+)',html).group(1))
n=int(sys.argv[1]) if len(sys.argv)>1 else cur
html=re.sub(r'\?v=\d+','?v=%d'%n,html);open('index.html','w').write(html)
core=['./','index.html','manifest.webmanifest','fonts.css?v=%d'%n]
for f in re.findall(r'(?:src|href)="([^"]+\.(?:js|css)\?v=\d+)"',html):core.append(f)
core=list(dict.fromkeys(core))
extra=sorted(glob.glob('fonts/*.woff2')+glob.glob('img/art/*.webp')+glob.glob('img/chart/*.webp')+['img/icon-192.png','img/icon-512.png','img/ship.jpg','img/nassau-day9.jpg','img/map-bahamas-florida-straits.jpg'])
sw="""/* generated by tools/mksw.py */
const V='fn-v%d';
const CORE=%s;
const EXTRA=%s;
self.addEventListener('install',e=>{e.waitUntil((async()=>{const c=await caches.open(V);await c.addAll(CORE);for(const u of EXTRA){try{await c.add(u)}catch(_){}}self.skipWaiting()})())});
self.addEventListener('activate',e=>{e.waitUntil((async()=>{for(const k of await caches.keys())if(k!==V)await caches.delete(k);await self.clients.claim()})())});
self.addEventListener('fetch',e=>{const r=e.request;if(r.method!=='GET'||new URL(r.url).origin!==location.origin)return;
 e.respondWith((async()=>{const c=await caches.open(V);const nav=r.mode==='navigate';
  if(nav){try{const f=await fetch(r);c.put('index.html',f.clone());return f}catch(_){return (await c.match('index.html'))||(await c.match('./'))}}
  const m=await c.match(r,{ignoreSearch:false})||await c.match(r,{ignoreSearch:true});if(m)return m;
  try{const f=await fetch(r);if(f.ok)c.put(r,f.clone());return f}catch(_){return new Response('',{status:504})}})())});
"""%(n,repr(core).replace("'",'"'),repr(extra).replace("'",'"'))
open('sw.js','w').write(sw);print('built v',n,len(core),'core',len(extra),'extra')
